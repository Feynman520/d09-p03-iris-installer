// 코덱스용 CA 번들 — 설계 A'(2026-09-18) 조각 2.
//
// TeamClaude 는 코덱스를 MITM(중간에서 여는) 전달 프록시 방식으로만 중계하고, 그때
// 쓰는 CA 증명서를 설정 파일 옆(`<portable-state>\teamclaude\teamclaude-ca.pem`)에
// **첫 가로채기 요청 때** 만든다. 코덱스 CLI(Rust)는 `SSL_CERT_FILE` 로 신뢰 목록을
// 받는데, rustls 는 이 변수가 있으면 시스템 신뢰 목록을 **대체**한다. CA 하나만 주면
// 중계기가 가로채지 않고 통과시키는 호스트(auth.openai.com 등)의 진짜 인증서가
// 실패하므로, Node 가 내장한 공인 루트 전부 + TeamClaude CA 를 한 파일로 묶어 준다.
//
// 이 파일은 순수 함수 + 얇은 파일 입출력만 갖는다(시험에서 memfs 로 대체).
import nodeFs from 'node:fs';
import path from 'node:path';
import tls from 'node:tls';

export const CA_FILE = 'teamclaude-ca.pem';
export const BUNDLE_FILE = 'codex-ca-bundle.pem';
export const BUNDLE_HEADER = '# IRIS codex-ca-bundle: Node root certificates + TeamClaude MITM CA. Generated by the installer -- do not edit.\n';

const PEM_RE = /^-----BEGIN CERTIFICATE-----\r?\n[\s\S]+?\r?\n-----END CERTIFICATE-----$/;

export function isPemCertificate(text) {
  return PEM_RE.test(String(text ?? '').trim());
}

/** 번들 본문. roots 는 시험에서 바꿔 끼울 수 있게 인수로 받는다. */
export function buildCaBundle(caPem, roots = tls.rootCertificates) {
  const ca = String(caPem ?? '').trim();
  if (!isPemCertificate(ca)) throw new Error('cabundle: teamclaude-ca.pem is not a PEM certificate');
  const list = Array.from(roots ?? [], (r) => String(r).trim()).filter(isPemCertificate);
  return `${BUNDLE_HEADER}${list.join('\n')}\n${ca}\n`;
}

/** 지금 번들이 이 CA 를 담고 있는가(CA 가 다시 만들어지면 거짓이 된다). */
export function bundleCovers(bundleText, caPem) {
  const ca = String(caPem ?? '').trim();
  return ca.length > 0 && String(bundleText ?? '').includes(ca);
}

/**
 * writeCaBundle(dir) -> { ok, changed, caPath, bundlePath, roots?, reason? }
 * CA 가 없으면 { ok:false, reason:'no-ca' } (중계기가 아직 가로채기 요청을 못 받은 것).
 * 번들이 이미 이 CA 를 담고 있으면 건드리지 않는다(멱등).
 */
export function writeCaBundle(dir, { fs = nodeFs, roots = tls.rootCertificates } = {}) {
  const caPath = path.join(dir, CA_FILE);
  const bundlePath = path.join(dir, BUNDLE_FILE);
  let caPem = null;
  try { caPem = fs.readFileSync(caPath, 'utf8'); } catch { /* not minted yet */ }
  if (caPem == null || !isPemCertificate(caPem)) return { ok: false, reason: 'no-ca', caPath, bundlePath };
  let current = null;
  try { current = fs.readFileSync(bundlePath, 'utf8'); } catch { /* first time */ }
  if (current != null && bundleCovers(current, caPem)) return { ok: true, changed: false, caPath, bundlePath };
  const text = buildCaBundle(caPem, roots);
  fs.writeFileSync(bundlePath, text, 'utf8');
  return { ok: true, changed: true, caPath, bundlePath, roots: Array.from(roots ?? []).length };
}
